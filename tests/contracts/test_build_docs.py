"""UX round 3 (plan §17.2 FR-2/FR-3): per-build click-through mock + technical appendix.

Both are regenerated by ``scripts/build_images.sh`` for every build and verified current by
``scripts/check.sh``; these contracts pin what they must (and must never) contain.
"""

from __future__ import annotations

import re
from pathlib import Path

import build_clickthrough
import check_bundle_leakage as scanner
import source_bundle

ROOT = Path(__file__).resolve().parents[2]
MOCK = ROOT / "docs" / "clickthrough" / "investigators_clickthrough.html"
APPENDIX = ROOT / "docs" / "TECHNICAL_APPENDIX.md"

SCREENS = (
    "consent",
    "background",
    "workspace-tour",
    "practice-team",
    "practice-assistant",
    "waiting-room",
    "workbench",
    "checkin",
    "time-up",
    "confidence",
    "peer-ratings",
    "questionnaire",
    # UX round 5, item 4: options-bearing items (the teammate-nature suspicion
    # check) sit on their own trailing screen, mirroring SessionItemsPage.
    "suspicion",
    "debrief",
    "data-use",
    "completion",
)


def test_docs_live_outside_the_source_bundle() -> None:
    bundled = {p.resolve() for p in source_bundle.iter_files()}
    assert MOCK.resolve() not in bundled
    assert APPENDIX.resolve() not in bundled


def test_mock_is_self_contained_and_never_reaches_a_live_agent() -> None:
    text = build_clickthrough.render()
    for pattern in (r"https?://", r"\bfetch\s*\(", "XMLHttpRequest", "WebSocket", "EventSource",
                    r"<script[^>]+src=", r"<link[^>]+href="):
        assert not re.search(pattern, text), pattern
    assert scanner.scan_text(text, "clickthrough") == []


def test_mock_walks_every_screen_with_ungated_navigation() -> None:
    text = build_clickthrough.render()
    ids = re.findall(r'<section class="screen[^"]*" id="([a-z-]+)"', text)
    assert tuple(ids) == SCREENS
    assert text.count("<!-- EDIT-ME: screen ") == len(SCREENS)
    # Next is a plain always-enabled control: nothing in the mock gates it.
    assert 'id="mock-next" type="button"' in text
    markup = re.sub(r"<style>.*?</style>", "", text, flags=re.S)
    # UX round 4: the practice chat/assistant composers render disabled — they are
    # previews, not try-its. Strip them before asserting no gate anywhere else.
    markup = re.sub(r'<div class="composer">.*?</div>', "", markup, flags=re.S)
    assert not re.search(r"\bdisabled\b", markup)
    # Both FR-1 interaction modes and both study families are reviewable.
    assert 'value="nl"' in text and 'value="structured"' in text
    assert 'value="pe"' in text and 'value="tp"' in text


