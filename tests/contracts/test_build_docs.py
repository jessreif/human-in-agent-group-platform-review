def test_mock_reflects_round4_ux() -> None:
    """UX_Feedback_v4: the mock tracks the retitled/preview-only practice flow,
    intel-on-its-own-card shares, the /7 check-in wording, greeting buttons and
    the pre-debrief choice item."""
    text = build_clickthrough.render()
    assert "Practice: Sharing intel with your team" in text
    assert "Practice: Interacting with the AI assistant" in text
    assert "Practice — sharing intel" not in text
    assert "Practice — the AI assistant" not in text
    assert "Ask the team</h2>" not in text  # item 4: preview only, no try-it
    assert 'class="intel-card"' in text  # item 9: intel is its own card
    assert "evidence currently in your case file" in text  # items 1 + 6
    assert "Time Pressure Reported at Check-in" in text  # item 12
    for greeting in (">Hello!</button>", ">Hi!</button>", ">Hey!</button>"):
        assert greeting in text  # item 8
    # item 14: the pre-debrief teammate-nature question with its four options.
    assert "Thinking about the other two members of your team" in text
    assert "All were human" in text and "All were automated" in text
    assert "I am not sure" in text


def test_appendix_is_stamped_and_free_of_recruitment_and_identity_details() -> None:
    text = APPENDIX.read_text(encoding="utf-8")
    assert "GENERATED by scripts/build_tech_appendix.py" in text
    assert re.search(r"Build source-bundle SHA-256: `[0-9a-f]{64}`", text)
    for word in ("prolific", "PROLIFIC_PID", "worker id", "initials:", "@university.edu", "$"):
        assert word.lower() not in text.lower(), word
    for section in ("Stage graph", "Commands and transactions", "Scheduler", "Generation pipeline",
                    "Participant projection", "Persistence", "Provenance"):
        assert section in text
