"""Builds transcript_viewer.html: a local, self-contained viewer for the N = 90 pilot transcripts.
Contains participant chat text, so keep it local (no research IDs are included).

Each teammate/system message gets a source label (src) — generated by the model vs scripted/fixed — and,
where the model's reply was rejected and a backup line went out instead, the rejected text (cf) and the
gate that rejected it (why). Model replies that finished after the deadline (quarantined) are added as
never-shown rows. Labels are also written to message_sources.csv."""
import glob, json, os, re
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
SAMPLES = ["data/pilot1", "data/pilot2"]
P = pd.read_csv(os.path.join(HERE, "participants.csv"))
C = pd.read_csv(os.path.join(ROOT, "coding", "participant_messages_coded.csv"))
codes = {r.message_id: (str(r.types) if pd.notna(r.types) else "", str(r.crates) if pd.notna(r.crates) else "") for r in C.itertuples()}
load = lambda kind: pd.concat([pd.read_csv(sorted(glob.glob(os.path.join(ROOT, f, f"investigators_{kind}_*")))[0]) for f in SAMPLES])
M = load("message"); E = load("event"); MC = load("model_call").drop_duplicates("call_id").set_index("call_id")
M = M[M.session_id.isin(P.session_id)].drop_duplicates("message_id")
M["t"] = pd.to_datetime(M.created_at, utc=True)
E = E.drop_duplicates("event_id"); E["p"] = E.payload.map(lambda s: json.loads(s) if isinstance(s, str) and s else {})

# --- message sources ----------------------------------------------------------------------------
ids = lambda typ, key: {p[key] for p in E[E.type == typ].p if p.get(key)}
greeting, share_card, sched_req = ids("voice_line_committed", "message_id"), ids("structured_response_delivered", "message_id"), ids("scripted_request_delivered", "request_id")
delivered_ms = {p["message_id"]: ms for p, ms in zip(E[E.type == "message_delivered"].p, E[E.type == "message_delivered"].active_ms) if p.get("message_id")}
norm = lambda s: re.sub(r"[^a-z0-9 ]", "", str(s).lower()).strip()
generated = {}
for sid, raw in MC[MC.status == "succeeded"][["session_id", "raw_response"]].itertuples(index=False):
    generated.setdefault(sid, set()).add(norm(raw))
REMARK = re.compile(r"^(yikes this is a lot|actually i'm on track|me too, feels like a lot|ok almost done with my|i am not!|ah not done with my|me either!)")
REDIRECT = re.compile(r"^(say the crate number|tell me which crate and i will|name the crate and i will)", re.I)
CRATE_LIST = re.compile(r"^(my crates are|i'm on crates)", re.I)
DISCLOSURE = re.compile(r"automated (teammate )?account", re.I)
WHY = {"evaluation": "judged the participant's work", "voice_format": "greeting opener / punctuation style", "near_repeat": "too close to an earlier line",
       "repeat_message": "repeated an earlier message"}

def source(m):
    b = str(m.body) if pd.notna(m.body) else ""
    if m.actor == "system": return "scripted", "System notice"
    if m.message_id in greeting: return "scripted", "Greeting reply"
    if m.message_id in share_card: return "scripted", "Share card"
    if REMARK.match(b): return "scripted", "Workload remark"
    if pd.notna(m.request_id) and m.request_id in sched_req: return "scripted", "Scheduled request"
    if norm(b) in generated.get(m.session_id, ()): return "generated", "Generated"
    if DISCLOSURE.search(b): return "fixed", "Bot disclosure"
    if REDIRECT.match(b): return "fixed", "Which-crate redirect"
    if CRATE_LIST.match(b): return "fixed", "Crate-list reply"
    return "backup", "Backup line (no model call logged)"

T = M[M.actor != "participant"]
src = {m.message_id: source(m) for m in T.itertuples()}

# Link each model call to what was shown. A generation's delivery lands at its plan's scheduled_ms, so match the
# first teammate message delivered in [scheduled_ms, scheduled_ms + 1.5 s] in that session. Three ways the model's
# own text never reached the chat: rejected by the output gate (backup line shown instead), an exact repeat of an
# earlier line (swapped for a backup line at delivery), or never delivered at all (late = quarantined, or still
# queued when the deadline swept the schedule).
cf, ghosts = {}, []
team_ms = {}
for m in T[T.actor.isin(["JT", "PM"])].itertuples():
    if m.message_id in delivered_ms: team_ms.setdefault(m.session_id, []).append((delivered_ms[m.message_id], m.message_id))
body = dict(zip(T.message_id, T.body.astype(str)))
swapped = {p["message_id"] for p in E[E.type == "message_delivered"].p if p.get("repeat_substituted")}
shown = {}
for sid, mid in zip(T.session_id, T.message_id): shown.setdefault(sid, set()).add(norm(body[mid]))
for e in E[E.type.isin(["generation_resolved", "generation_quarantined"])].itertuples():
    p = e.p
    if p.get("call_id") not in MC.index: continue
    call = MC.loc[p["call_id"]]; raw = str(call.raw_response)
    if p.get("status") == "quarantined":
        ghosts.append(dict(session_id=e.session_id, active_ms=int(e.active_ms), b=raw, lab="Never shown (finished after the deadline)")); continue
    sched = (p.get("plan") or {}).get("scheduled_ms")
    hits = [mid for ms, mid in sorted(team_ms.get(e.session_id, [])) if sched is not None and sched <= ms <= sched + 1500
            and mid not in cf and src[mid][0] not in ("scripted",)]
    if p.get("status") == "succeeded":
        if any(norm(body[h]) == norm(raw) for h in hits): continue
        sw = [h for h in hits if h in swapped]
        if sw: cf[sw[0]] = (raw, "exact repeat of an earlier message", "repeat_substituted", "Backup line (model reply was a repeat)")
        elif norm(raw) not in shown.get(e.session_id, ()):
            ghosts.append(dict(session_id=e.session_id, active_ms=int(sched or e.active_ms), b=raw, lab="Never shown (still queued at the deadline)"))
        continue
    viol = json.loads(call.validation).get("violations", []) if isinstance(call.validation, str) else []
    if hits:
        cf[hits[0]] = (raw, "; ".join(WHY.get(v, v) for v in viol), ", ".join(viol), "Backup line (model reply rejected)")
for mid, (raw, why, code, lab) in cf.items():
    src[mid] = ("backup", lab)

out = [dict(sample=s, session_id=m.session_id, message_id=m.message_id, actor=m.actor, body=m.body, source=src[m.message_id][1],
            model_reply_not_shown=cf.get(m.message_id, ("",) * 4)[0], why_not_shown=cf.get(m.message_id, ("",) * 4)[2])
       for s, m in zip(T.session_id.map(P.set_index("session_id")["sample"]), T.itertuples())]
pd.DataFrame(out).to_csv(os.path.join(HERE, "message_sources.csv"), index=False)

# --- viewer data --------------------------------------------------------------------------------
def val(v):
    if pd.isna(v): return None
    return v.item() if hasattr(v, "item") else v

sessions = []
for p in P.itertuples():
    g = M[M.session_id == p.session_id].sort_values(["t", "accepted_seq"])
    t0 = g.t.min()
    msgs = []
    for m in g.itertuples():
        ty, cr = codes.get(m.message_id, ("", ""))
        d = dict(s=round((m.t - t0).total_seconds()), a=m.actor, ch=m.channel, b=str(m.body) if pd.notna(m.body) else "", code=ty, crates=cr, crate=val(m.crate))
        if m.message_id in src: d["src"], d["lab"] = src[m.message_id]
        if m.message_id in cf: d["cf"], d["why"] = cf[m.message_id][:2]
        msgs.append(d)
    # Quarantined replies: no seat or wall time is logged, so place them at the end of the transcript.
    end = msgs[-1]["s"] if msgs else 0
    msgs += [dict(s=end, a="Teammate", ch="team", b="", src="ghost", lab=x["lab"], cf=x["b"], why="")
             for x in ghosts if x["session_id"] == p.session_id]
    d = {k: val(getattr(p, k)) for k in ["sample", "session_id", "cell", "overlap", "casefile", "workload", "light_seat", "JT_level", "PM_level", "own_workload",
         "n_msgs", "n_req_msgs", "any_req", "n_shares", "n_sched_fulfilled", "correct_total", "correct_own", "correct_team", "conf_mean",
         "tp_post_05", "tp_post_07", "tp_post_08", "tp_post_10", "tp_post_12", "oe_crate_strategy", "oe_source_reliance"]}
    d["msgs"] = msgs
    sessions.append(d)

html = open(os.path.join(HERE, "transcript_viewer_template.html")).read().replace("/*DATA*/null", json.dumps(sessions).replace("</", "<\\/"))
open(os.path.join(HERE, "transcript_viewer.html"), "w").write(html)
labs = pd.Series([v[1] for v in src.values()]).value_counts()
print(len(sessions), "sessions,", sum(len(s["msgs"]) for s in sessions), "messages;", len(cf), "backup lines with the model reply,", len(ghosts), "never shown")
print(labs.to_string())
