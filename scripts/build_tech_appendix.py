#!/usr/bin/env python3
"""Generate the per-build technical appendix (UX round 3, FR-3; plan §17.2).

    uv run --project backend --frozen python scripts/build_tech_appendix.py          # write
    uv run --project backend --frozen python scripts/build_tech_appendix.py --check  # verify

Writes ``docs/TECHNICAL_APPENDIX.md``: a reader-oriented description of how the application
is built — components, profile binding, stage graph, command/transaction model, scheduler,
generation pipeline, persistence and provenance. Every table is introspected from the code
it describes, and the document is stamped with the build's source-bundle checksum, so a
stale appendix fails ``scripts/check.sh``. ``docs/`` is outside the source bundle, so writing
the appendix never changes the hash it records.

Deliberately excluded: recruitment-platform details, participant identifiers, payment
amounts and anything about individual sessions.
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT / "scripts"))

OUT = ROOT / "docs" / "TECHNICAL_APPENDIX.md"


def _source_sha() -> str:
    import source_bundle  # scripts/source_bundle.py

    return str(source_bundle.aggregate(source_bundle.manifest()))


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out + [""]


def _code(values: object) -> str:
    items = sorted(values) if isinstance(values, (set, frozenset)) else list(values)  # type: ignore[call-overload]
    return ", ".join(f"`{v}`" for v in items) if items else "—"


def render() -> str:
    from app.services import projection
    from app.db import schema as s
    from app.db.engine import expected_schema_head
    from app.db.export import EXPORT_EXCLUDED_TABLES
    from app.domain.manifests import cli
    from app.domain.manifests.binding import bind
    from app.domain.manifests.schema import ALL_CHANNELS, GENERATIVE_CLASSES
    from app.domain.manifests.store import ContentStore
    from app.domain.stage_graph import EDGES
    from app.services import engines, lifecycle, prompts, scheduler

    store = ContentStore(ROOT / "content")
    sha = _source_sha()
    lines: list[str] = [
        "# Investigators — technical appendix",
        "",
        "<!-- GENERATED by scripts/build_tech_appendix.py — do not edit by hand. -->",
        "",
        f"- Build source-bundle SHA-256: `{sha}`",
        f"- Database schema head: `{expected_schema_head()}`",
        f"- Prompt builder: `{prompts.PROMPT_BUILDER_VERSION}` · "
        f"teammate output validator: `{engines.VALIDATOR_VERSION}`",
        "",
        "This appendix describes how the Investigators experiment application is implemented, "
        "for readers who need to understand or audit the system. It is regenerated for every "
        "build; its tables are read from the code they describe. It intentionally omits "
        "recruitment-platform integration, participant identifiers and payment details.",
        "",
        "## 1. Components",
        "",
        "- **API** (`backend/app`, FastAPI + SQLAlchemy Core on PostgreSQL): the participant "
        "and admin HTTP surfaces. Every participant mutation is a *command* executed in one "
        "transaction that first locks the session row (`SELECT ... FOR UPDATE`, "
        "`app.db.tx.execute_command`), so commands for one session apply strictly in order.",
        "- **Worker** (`app.workers.main`): claims scheduled jobs. A dispatch thread runs "
        "timing jobs (warnings, deadlines, deliveries, check-ins); a separate generation "
        "thread runs model-backed `generate` jobs so a slow model call never delays a due "
        "timing job.",
        "- **Local model** (Ollama, loopback only): grounded generation for teammate social "
        "replies and the AI assistant, pinned by model digest; every output passes a "
        "deterministic validator and falls back to pinned scripted text on any failure.",
        "- **UI** (`frontend`, React + Vite, static nginx image): a server-driven stage "
        "router. The simultaneous workbench mounts case file, team chat and AI assistant "
        "at once; all state transitions arrive through the event feed and session snapshot.",
        "",
        "## 2. Profiles, binding and policy",
        "",
        "A session pins one published *manifest* (profile) and its content artifacts by "
        "SHA-256 (`content/published/manifests.json` is add-only). Binding resolves the "
        "manifest to an executable `ResolvedPolicy`; its canonical hash "
        "(`behavior_policy_hash`) is part of each session's compatibility key. The two arms "
        "of a profile may differ only under `manipulation.arm.*` (checked on every build).",
        "",
        "New live batch groups may pin an optional, versioned `enrollment_policy`: "
        "an allowed platform, exact member/arm cells, and a valid-completer target per cell. "
        "Consenting participants receive a random tie-break among the least-occupied "
        "eligible cells. Retained-data completions and active allocated sessions hold "
        "capacity; terminal dropouts release capacity without changing their old allocation. "
        "The allocator and completion handler serialize on the group row, after the "
        "participant's own session lock. The group closes when every target is reached. "
        "Uncapped historical groups retain their existing permuted-block behavior. "
        "A separate test-only policy requires TEST_ IDs, records zero-cent ineligible "
        "entitlements, and excludes these sessions from the compensation queue.",
        "",
    ]
    rows = []
    for mid in cli.PROFILES:
        m = bind(store, mid, mode="preview").manifest
        checkin = m.timing.checkin
        rows.append(
            [
                f"`{mid}`",
                m.study_key.replace("investigators_", ""),
                m.profile_kind,
                f"`{m.interaction_mode}`",
                "—" if checkin is None else ("optional" if checkin.own_rating_skippable else "required"),
                m.teammates.social_generation,
                " → ".join(f"{p.name} {p.from_active_s}–{p.until_active_s}s" for p in m.channels.phases),
            ]
        )
    lines += _table(
        ["Profile", "Study", "Kind", "Interaction mode", "Own pressure rating", "Social text", "Channel phases"],
        rows,
    )
    lines += [
        "The **interaction mode** feature flag (FR-1) is arm-invariant. `structured_and_nl` "
        "offers per-crate request controls plus free text; `nl_only` never opens "
        "`structured_seeking` and refuses crate-only assistant asks "
        "(`structured_request_disabled`) — a typed teammate ask naming a crate instead "
        "routes each responder into per-seat structured retrieval, delivering that "
        "seat's own latest record card (O-1). The participant projection exposes only "
        "a neutral `structured_requests` boolean.",
        "",
        f"Channels: {_code(ALL_CHANNELS)}. Generative response classes: {_code(GENERATIVE_CLASSES)}.",
        "",
        "## 3. Stage graph",
        "",
        "Stages are server-owned; a transition is legal only along these edges "
        "(`app.domain.stage_graph.EDGES`). Every non-terminal stage may also end in "
        "`withdrawn`, `technical_stop` or `abandoned` (omitted below).",
        "",
    ]
    exceptional = {"withdrawn", "technical_stop", "abandoned"}
    for variant, edges in EDGES.items():
        lines.append(f"**{variant}**")
        lines.append("")
        rows = [
            [f"`{src}`", _code(set(dst) - exceptional)]
            for src, dst in edges.items()
            if set(dst) - exceptional
        ]
        lines += _table(["From", "To"], rows)
    lines += [
        "## 4. Commands and transactions",
        "",
        "Each command carries a client UUID and the expected session revision. The handler "
        "runs inside one transaction that appends events, updates projections, schedules "
        "jobs and writes a *receipt*; replaying the same UUID returns the stored receipt, and "
        "a stale revision is refused (`stale_revision`) so the client resyncs and retries "
        "under a new UUID. Bodies are bounded (64 KiB) and validated before any state is "
        "touched. Command kinds and the stages that accept them:",
        "",
    ]
    lines += _table(
        ["Command", "Accepted in stages"],
        [[f"`{k}`", _code(v)] for k, v in sorted(lifecycle.COMMAND_STAGES.items())],
    )
    job_kinds = re.findall(r'if kind == "([a-z_]+)"', inspect.getsource(scheduler.dispatch))
    lines += [
        "## 5. Scheduler and timing",
        "",
        "Time-dependent behavior is a durable `scheduled_job` row with a logical key, a clock "
        "basis (`active` task time, which pauses during check-ins, or `wall`) and a lease. "
        "Workers claim due jobs with `FOR UPDATE SKIP LOCKED`, execute them inside the "
        "session transaction (`finish_job`), and expired leases are reclaimed; retries reuse "
        "the job's pinned inputs so outcomes never re-roll. Job kinds:",
        "",
        _code(job_kinds),
        "",
        "## 6. Generation pipeline",
        "",
        "0. Free-text team messages route first: `engines.addressed_seats` picks the responder "
        "set (addressed seat, or both seats for broadcast/undirected text — O-2). Automation "
        "probes get a pinned verbatim disclosure line without a model call (O-3), answered by "
        "the seat the probe is about (`probed_seats` — a third-person \"is pm a bot?\" "
        "discloses from PM, relational \"is your teammate a bot?\" resolves to the other "
        "seat, coordinated \"are you and pm bots?\" hits both — O-11/BA-65/BA-66); a probe "
        "can never be refused by the ordinary pending-request cap or the operational "
        "rate limit and is always logged as an `automation_probe` event — disclosure "
        "*scheduling* instead gets its own bounded per-seat budget of unfinished "
        "(pending or claimed) probe lines (BA-75). Probe-adjacent "
        "non-fires flag `probe_near_miss` on `message_accepted` for review (O-12/BA-67). "
        "In `nl_only` a typed intel ask routes each responder into per-seat record "
        "delivery (crate references accept digits, number words, ordinals and `#N`; a "
        "bare crate-numbered follow-up counts as the ask; a leading seat address like "
        "\"jt, crate 3\" scopes it to that seat; multi-clause messages resolve the "
        "crate in the *asking* clause — \"i have crate 3. what about crate 4?\" asks "
        "about 4 — BA-52/O-12/BA-62/BA-64), while in structured "
        "modes the same ask gets the deterministic picker-redirect line (BA-53/BA-63); "
        "first-person statements (\"i have crate 3\") are not asks (BA-64); "
        "assignment/no-holdings asks get grounded verbatim lines — none of these schedule "
        "a `generate` job.",
        "1. On accept, the command pins a `knowledge_snapshot` (record ids + SHA-256 for the "
        "assistant; open request episodes for teammates) and schedules a `generate` job.",
        "2. The generation thread builds a grounded prompt from the snapshot only "
        "(`app.services.prompts`): untrusted text is quoted inside `<<< >>>` blocks with "
        "delimiters escaped; teammate prompts carry the seat's style block, a bounded RECENT "
        "CHAT window of the latest multi-actor team turns — including participant share "
        "events, which never write a message row (BA-68) — with card deliveries and "
        "shares shown as `[shared a record card on crate N]` placeholders (O-14), an "
        "OPEN ASKS block scoped to asks the responding seat is part of (BA-69), and its "
        "own earlier team lines as no-repeat context (cards as placeholders there too) — "
        "record bodies never reach a social prompt (AID-55).",
        "3. The provider call has one end-to-end deadline (identity check, queue, HTTP, "
        "bounded body read). Each call carries a per-job `derived_seed(session_id, "
        "job_id)` forwarded as the OpenAI `seed`, and `model_call.parameters` records "
        "the seed plus the load the call competed with (`concurrent_sessions`, "
        "`claimed_generate`, `queued_generate`, `provider_inflight_local` — O-18/O-20; "
        "`claimed_generate` counts scheduler-claimed jobs across workers (DB-level), "
        "`provider_inflight_local` the adapter's process-local in-flight counter — "
        "BA-70). Failed calls persist the effective request params, the seed, a "
        "`dispatched` marker distinguishing pre-wire from on-wire failures "
        "(connection refusals and DNS failures count as never-dispatched), and "
        "measured latency (BA-71).",
        "4. Inside the session lock the output is validated; the assistant's location "
        "claims are also checked against the pinned records. A rejected, empty, failed or "
        "late output is recorded on `model_call` and replaced by deterministic fallback "
        "text (fallback lines also skip anything already sent; a pool that exhausts wraps "
        "to its start, recorded via `draw_ordinal`/`pool_wrapped` on "
        "`voice_line_committed` and `repeated_line` on `message_delivered` — O-17).",
        "5. A `deliver` job commits the message at its scheduled active time.",
        "",
    ]
    violations = sorted(
        set(re.findall(r'violations\.append\("([a-z_]+)"\)', inspect.getsource(engines)))
        | set(re.findall(r'violations\.append\("([a-z_]+)"\)', inspect.getsource(scheduler)))
    )
    lines += [
        f"Validator `{engines.VALIDATOR_VERSION}` violation classes: {_code(violations)}. "
        f"Repeat rule (BA-60): generated text and pool-drawn fallback lines of at least "
        f"{engines.REPEAT_MIN_WORDS} words may never be sent twice by teammates in a session "
        "(comparison ignores case, spacing, apostrophes and hyphens — BA-57). The "
        f"`near_repeat` class (v7, 2026-10-04 lab walkthrough) also rejects a line of at "
        f"least {engines.NEAR_REPEAT_MIN_WORDS} distinct words sharing ≥"
        f"{engines.NEAR_REPEAT_DICE:.0%} distinct-word Dice overlap with a delivered "
        "line — convergent cross-seat near-paraphrases read as one scripted reply. If a "
        "repeat or near-paraphrase is detected at delivery, an unused pool line (itself "
        "skipping exact and near repeats) is substituted and the event is flagged "
        "`repeat_substituted` + `repeat_substituted_reason` (\"exact\"/\"near\"); a "
        "repeat that still ships flags `repeated_line`/`near_repeat_line` on "
        "`message_delivered` (O-17). Pinned *verbatim* lines — the automation disclosure, "
        "grounded assignment/no-holdings statements and the picker redirect — are exempt by "
        "design: their truth and consistency outrank variety.",
        "",
        "Teammate voices (prompt builder style blocks):",
        "",
    ]
    lines += [f"- **{seat}** — {text}" for seat, text in prompts.SEAT_STYLES.items()]
    lines += [
        "",
        "### 6.1 Task-shape conditions (crate distribution experiment)",
        "",
        "The `task` block of a manifest can pin a non-legacy world shape "
        "(`overlap_v1` generator): `crate_overlap` (`none` = 12 crates with "
        "disjoint four-crate seat assignments, `some` = 8 crates with all three "
        "pairwise assignment intersections held to 1–2 crates, `full` = 4 crates "
        "shared by every seat) and `participant_intel_budget` (20 — the only "
        "supported thin-file value). The administered shape persists in "
        "`world_snapshot.content.world_params` (`n_crates`, `n_assigned`, "
        "`crate_overlap`, `participant_intel_budget`, `covered_unassigned`) and "
        "every consumer — workbench descriptors, replay, exports, the power "
        "workflow — resolves it snapshot-first, never from deployment flags.",
        "",
        "**Comparability note (audit G04):** the conditions hold the "
        "experimental constants fixed — four assigned crates per participant, "
        "two own-file and two team-dependent solvability roles, six hideouts, "
        "and the latest-record truth rule. What varies is the surrounding "
        "world: total crate count (4/8/12), participant file density (full "
        "world ≈47–49 records vs the 20-record thin file), the count of "
        "unassigned crates the participant's file covers (all unassigned "
        "crates under legacy/`some`, a limited asked-plus-fill set under "
        "`none`, none under `full`), and which crates scripted teammate asks "
        "can target (full-overlap seats can only ask about the shared four). "
        "`crate_overlap` and `intel_budget` are therefore *experimental "
        "factors*, not nuisance covariates: they must appear as stratification "
        "or factor terms in any approved pooled analysis, and the power "
        "workflow refuses mixed-cell inputs absent an explicit condition spec. "
        "Accuracy denominators are unchanged (four assigned crates), but "
        "seeking opportunities, file coverage measures and the request "
        "surface differ by design across levels.",
        "",
        "## 7. Participant projection",
        "",
        "Participants only ever receive allowlisted event types and payload keys "
        "(`app.services.projection.PARTICIPANT_EVENTS`); arm labels, truth, teammate holdings "
        "and implementation vocabulary never leave the server, and the built bundle is "
        "scanned for leaked vocabulary on every gate. Allowlisted event types:",
        "",
        _code(projection.PARTICIPANT_EVENTS),
        "",
        "## 8. Persistence",
        "",
        "All tables live in the `app` schema; migrations are Alembic, and the API refuses "
        "readiness when the database head differs from the build's. Export boundaries "
        "(BA-60): a research export contains committed rows from session-owned `app` "
        "tables only — it omits "
        f"{_code(EXPORT_EXCLUDED_TABLES)} (participant display initials are "
        "identity-adjacent and never leave), all `identity.*` tables (platform linkage), "
        "and payment-domain tables (entitlement, receipt, result). Platform linkage plus "
        "payment state appears only in the restricted compensation product "
        "(`export_payment_linkage` / `app.export.restricted`), which must run as the "
        "`investigators_compensation` role and returns nothing else session-owned. Drift "
        "guards in `app.export.study` fail the export if a restricted or display table "
        "ever becomes passthrough.",
        "",
    ]
    lines += _table(
        ["Table", "Columns"],
        [[f"`{t.name}`", str(len(t.columns))] for t in sorted(s.metadata.sorted_tables, key=lambda t: t.name)],
    )
    lines += [
        "## 9. Provenance and builds",
        "",
        "There is no Git tree: a build is identified by the SHA-256 over `backend/`, "
        "`frontend/`, `content/` and `docker-compose.yml` (`scripts/source_bundle.py`). Images "
        "are stamped with it and report it on API `/version` and UI `version.json`; pinned "
        "inputs are verified against `docs/baseline/SOURCE_CHECKSUMS.sha256`. Each build "
        "also regenerates this appendix and the click-through mock "
        "(`docs/clickthrough/investigators_clickthrough.html`).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the appendix is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"FAIL: {OUT.relative_to(ROOT)} is stale; run scripts/build_tech_appendix.py")
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
