#!/usr/bin/env python3
"""Write docs/MATERIALS from the content tree and the arm checker.

Run with a Python 3.12 environment that can import ``backend/app``
(the backend dependencies from ``backend/uv.lock``):

    cd backend && python ../scripts/build_materials_docs.py

The arm diff is whatever ``check_paired_arms`` returns. Re-run this script
rather than editing the markdown by hand.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

from app.domain.manifests.diff import check_paired_arms  # noqa: E402
from tests.wp02 import bound  # noqa: E402

OUT = ROOT / "docs" / "MATERIALS"
PAIR = ("tp_ai_v7", "tp_scripted_v9")


def _json_docs(path: Path) -> list[Path]:
    return sorted(p for p in path.rglob("*.json") if p.is_file())


def banks() -> str:
    lines = [
        "# Banks",
        "",
        "Generated by `scripts/build_materials_docs.py`. Sizes are the count of",
        "string leaves under each JSON file, not a hand count.",
        "",
        "| File | String leaves |",
        "|---|---|",
    ]

    def leaves(node: object) -> int:
        if isinstance(node, str):
            return 1
        if isinstance(node, dict):
            return sum(leaves(v) for v in node.values())
        if isinstance(node, list):
            return sum(leaves(v) for v in node)
        return 0

    for path in _json_docs(ROOT / "content" / "scripts"):
        data = json.loads(path.read_text(encoding="utf-8"))
        rel = path.relative_to(ROOT).as_posix()
        lines.append(f"| `{rel}` | {leaves(data)} |")
    lines += [
        "",
        "The reference pair's request bank is `content/scripts/requests.demo.v4.json`.",
        "The word demo in that id is historical. Pressure remarks for the",
        "reference pair are `content/scripts/remarks.tp_pressure.v1.json`.",
        "Selection is seeded. See `backend/app/domain/rng.py` and the scheduler.",
        "",
    ]
    return "\n".join(lines)


def checks() -> str:
    src = (BACKEND / "app" / "services" / "engines.py").read_text(encoding="utf-8")
    tree = ast.parse(src)
    found: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == "validate_teammate_output":
            for sub in ast.walk(node):
                if (
                    isinstance(sub, ast.Constant)
                    and isinstance(sub.value, str)
                    and sub.value.endswith("_leak")
                    or (
                        isinstance(sub, ast.Constant)
                        and isinstance(sub.value, str)
                        and sub.value
                        in {
                            "interface_leak",
                            "prompt_reveal",
                            "condition_leak",
                            "disrespect",
                            "human_claim",
                            "record_ref_leak",
                            "urgency",
                            "evaluation",
                            "task_advice",
                            "stall_excuse",
                            "voice_format",
                            "banned_token_reuse",
                            "length_overrun",
                            "hideout_leak",
                        }
                    )
                ):
                    if sub.value not in found:
                        found.append(sub.value)
    lines = [
        "# Checks",
        "",
        "Generated from `validate_teammate_output` in `backend/app/services/engines.py`.",
        "A hit appends the label and the function returns the list. The caller",
        "does not retry. The bank line is what the participant sees.",
        "Repetition is not in this function. It is rechecked at delivery.",
        "",
        "| Label | How | Action | Function |",
        "|---|---|---|---|",
    ]
    for name in found:
        lines.append(
            f"| `{name}` | rule or pattern in `engines.py` | do not deliver the model text | `validate_teammate_output` |"
        )
    lines.append("")
    return "\n".join(lines)


def profiles() -> str:
    published = json.loads((ROOT / "content" / "published" / "manifests.json").read_text(encoding="utf-8"))
    manifests = published["manifests"]
    lines = [
        "# Profiles",
        "",
        f"Published manifests in `content/published/manifests.json`: {len(manifests)}.",
        f"Profile JSON files: {len(list((ROOT / 'content' / 'profiles').rglob('*.json')))}.",
        "",
        "Reference pair: the model and bank-only versions of the time-pressure study. Hashes are copied from the publication index by this script.",
        "",
        "| Profile | manifest_sha256 | bundle_sha256 |",
        "|---|---|---|",
    ]
    for name in PAIR:
        row = manifests[name]
        lines.append(f"| `{name}` | `{row['manifest_sha256']}` | `{row['bundle_sha256']}` |")
    lines += ["", "## Arm diff from `check_paired_arms`", ""]
    for name in PAIR:
        entries = check_paired_arms(bound(name))
        lines.append(f"### `{name}`")
        lines.append("")
        if not entries:
            lines.append("The checker returned no differences.")
        for entry in entries:
            lines.append(f"- `{entry.path}`: left `{entry.left!r}` / right `{entry.right!r}`")
        lines.append("")
    lines.append(
        "Anything not under `manipulation.arm` would have raised. This output is the allowed difference set."
    )
    lines.append("")
    return "\n".join(lines)


def instruments() -> str:
    lines = [
        "# Instruments",
        "",
        "Each file is the participant-facing instrument or a version of one.",
        "Item text is in the JSON. This list is the inventory, not a retyping of every item.",
        "",
        "| File |",
        "|---|",
    ]
    for path in _json_docs(ROOT / "content" / "instruments"):
        lines.append(f"| `{path.relative_to(ROOT).as_posix()}` |")
    lines.append("")
    return "\n".join(lines)


def prompts() -> str:
    text = (BACKEND / "app" / "services" / "prompts.py").read_text(encoding="utf-8")
    version = "unknown"
    for line in text.splitlines():
        if line.startswith("PROMPT_BUILDER_VERSION"):
            version = line.split("=", 1)[1].strip()
    return "\n".join(
        [
            "# Prompts",
            "",
            f"`PROMPT_BUILDER_VERSION` in `backend/app/services/prompts.py` is {version}.",
            "",
            "Social replies are assembled by `render_social` and `build_request`.",
            "The assistant prompt is `render_assistant`. Task solutions are not put in the social prompt.",
            "",
            "Decoding constants live in `backend/app/services/generation_policy.py`:",
            "temperature 0.2, max_tokens 400, reasoning_effort none_when_supported.",
            "top_p, top_k, context length, and stop sequences are not set there.",
            "",
        ]
    )


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "banks.md").write_text(banks(), encoding="utf-8")
    (OUT / "checks.md").write_text(checks(), encoding="utf-8")
    (OUT / "profiles.md").write_text(profiles(), encoding="utf-8")
    (OUT / "instruments.md").write_text(instruments(), encoding="utf-8")
    (OUT / "prompts.md").write_text(prompts(), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
